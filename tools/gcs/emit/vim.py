        ("Boolean", r("boolean"), "s:none", "NONE", ""),
        ("Identifier", r("variable"), "s:none", "NONE", ""),
        ("Function", r("function"), "s:none", "NONE", ""),
        ("Statement", r("keyword"), "s:none", "NONE", ""),
        ("Conditional", r("keyword-ctrl"), "s:none", "NONE", ""),
        ("Repeat", r("keyword-ctrl"), "s:none", "NONE", ""),
        ("Label", r("label"), "s:none", "NONE", ""),
        ("Operator", r("operator"), "s:none", "NONE", ""),
        ("Keyword", r("keyword"), "s:none", "NONE", ""),
