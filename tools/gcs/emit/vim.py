        ("Include", r("preprocessor"), "s:none", "NONE", ""),
        ("Define", r("preprocessor"), "s:none", "NONE", ""),
        ("Macro", r("preprocessor"), "s:none", "NONE", ""),
        ("PreCondit", r("preprocessor"), "s:none", "NONE", ""),
        ("Type", r("type"), "s:none", "NONE", ""),
        ("StorageClass", r("keyword"), "s:none", "NONE", ""),
        ("Structure", r("class"), "s:none", "NONE", ""),
