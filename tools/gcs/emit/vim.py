        ("Ignore", "s:faint", "s:none", "NONE", ""),
        ("Error", err, "s:none", "NONE", ""),
        ("Todo", r("keyword"), "s:surface0", "s:bold", ""),
        # Neovim diagnostics
        ("DiagnosticError", err, "s:none", "NONE", ""),
        ("DiagnosticWarn", warn, "s:none", "NONE", ""),
        ("DiagnosticInfo", info, "s:none", "NONE", ""),
        ("DiagnosticHint", "s:subtext", "s:none", "NONE", ""),
        ("DiagnosticOk", ok, "s:none", "NONE", ""),
        ("DiagnosticUnderlineError", "s:none", "s:none", "undercurl", f"{err}[0]"),
        ("DiagnosticUnderlineWarn", "s:none", "s:none", "undercurl", f"{warn}[0]"),
        ("DiagnosticUnderlineInfo", "s:none", "s:none", "undercurl", f"{info}[0]"),
        ("DiagnosticUnderlineHint", "s:none", "s:none", "undercurl", "s:subtext[0]"),
