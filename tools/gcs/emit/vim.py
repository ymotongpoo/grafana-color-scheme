"""Vim and Neovim colorschemes.

Both guifg/guibg and ctermfg/ctermbg are defined so the scheme works with or
without truecolor. `set termguicolors` is deliberately NOT called from here:
it is the user's decision and turning it on unasked breaks plain Vim inside
tmux. The README says what to add.

Neovim's treesitter captures and Diagnostic* groups are covered in the same
vimscript file, so no Lua module is needed to get a current-looking Neovim.
"""

