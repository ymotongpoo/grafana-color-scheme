        ("Directory", r("type"), "s:none", "s:bold", ""),
        ("Title", r("heading"), "s:none", "s:bold", ""),
        ("ErrorMsg", err, "s:none", "s:bold", ""),
        ("WarningMsg", warn, "s:none", "NONE", ""),
        ("ModeMsg", "s:fg", "s:none", "s:bold", ""),
        ("MoreMsg", ok, "s:none", "NONE", ""),
        ("Question", r("keyword"), "s:none", "NONE", ""),
        ("MsgArea", "s:fg", "s:none", "NONE", ""),
        ("MsgSeparator", "s:surface1", "s:none", "NONE", ""),
        ("StatusLine", "s:fg", "s:surface0", "NONE", ""),
        ("StatusLineNC", "s:faint", "s:mantle", "NONE", ""),
