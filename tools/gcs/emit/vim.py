        ("Special", r("string-escape"), "s:none", "NONE", ""),
        ("SpecialChar", r("string-escape"), "s:none", "NONE", ""),
        ("Tag", r("tag"), "s:none", "NONE", ""),
        ("Delimiter", r("punctuation"), "s:none", "NONE", ""),
        ("SpecialComment", r("comment-doc"), "s:none", "s:italic", ""),
