"""Emacs custom themes.

The `-theme.el` suffix is mandatory: Emacs derives the theme symbol from the
basename. The first form in the file must be `deftheme` and the last
`provide-theme`.

One display spec, `((class color) (min-colors 89))`, so the theme works in
GUI and in any terminal Emacs believes has enough colors. A 256-color
terminal gets Emacs's own approximation of these hexes, which is the tradeoff
every modern theme makes; a per-face dual spec would roughly triple the file
for a case that is increasingly rare.
"""

