def _theme(p: Palette, v: Variant) -> str:
    bindings = _let_bindings(v)
    width = max(len(name) for name, _ in bindings)
    let_lines = []
    let_lines.append("(let ((class '((class color) (min-colors 89)))")
    for i, (name, hexv) in enumerate(bindings):
        pad = name.ljust(width)
        prefix = "      " if i or True else ""
        let_lines.append(f'{prefix}({pad} "{hexv}")')
    let_lines[-1] = let_lines[-1] + ")"

    face_lines = []
    for face, attrs in _faces(v):
        face_lines.append(f"   `({face} ((,class ({attrs}))))")

    ansi = v.ansi("dim")
    vector = " ".join(f'"{ansi[i]}"' for i in (0, 1, 2, 3, 4, 5, 6, 7))

    return f"""\
;;; {v.id}-theme.el --- {v.label} -*- lexical-binding: t; -*-

;; Copyright (c) 2026 {p.scheme['author']}

;; Author: {p.scheme['author']}
;; URL: {p.scheme['homepage']}
;; Version: 1.0.0
;; Package-Requires: ((emacs "26.1"))
;; Keywords: faces, theme
;; SPDX-License-Identifier: {p.scheme['license']}

;;; Commentary:

;; {v.label}, derived from the Grafana Labs brand palette.  Every syntax
;; token clears WCAG AA (4.5:1) against the background, and comments are
;; kept clear of the threshold so they read as prose rather than as noise.
;;
;; {HEADER}
;; This is not an official Grafana Labs project.

;;; Code:

(deftheme {v.id}
  "{v.label}, a dim color scheme from the Grafana Labs brand palette.")

{chr(10).join(let_lines)}

  (custom-theme-set-faces
   '{v.id}

{chr(10).join(face_lines)})

  (custom-theme-set-variables
   '{v.id}
   `(ansi-color-names-vector [{vector}])))

;;;###autoload
(when (and (boundp 'custom-theme-load-path) load-file-name)
  (add-to-list 'custom-theme-load-path
               (file-name-as-directory (file-name-directory load-file-name))))

(provide-theme '{v.id})

;;; {v.id}-theme.el ends here
"""


def emit(p: Palette) -> dict[str, str]:
    return {f"{v.id}-theme.el": _theme(p, v) for _n, v in p.each()}
