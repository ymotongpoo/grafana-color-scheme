def _let_bindings(v: Variant) -> list[tuple[str, str]]:
    out: list[tuple[str, str]] = []
    for key in ("crust", "mantle", "base", "surface0", "surface1", "surface2"):
        out.append((key.replace("_", "-"), v.surfaces[key]))
    for key in ("bright", "fg", "subtext", "faint"):
        out.append((key, v.text[key]))
    for key, val in v.accents.items():
        out.append((key, val))
    return out


