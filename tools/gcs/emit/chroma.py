"""Chroma styles and stylesheets.

Two artifacts per variant, because Chroma has two consumer populations:

  styles/*.xml  Go programs can load these at runtime with
                chroma.NewXMLStyle, and it is the file shape the upstream
                `styles/` directory expects if this is ever contributed.

  css/*.css     Hugo CANNOT load a custom Chroma XML -- markup.highlight.style
                only accepts names compiled into Hugo. Hugo users need
                pre-generated classes plus `noClasses = false`.

The XML filename stem must equal the lowercased style name; upstream Chroma
has a test asserting that invariant.
"""

from __future__ import annotations

from ..palette import Palette, Variant
from . import chroma_tokens as T

HEADER = "Generated by tools/generate.py from palette.toml. Do not edit."


