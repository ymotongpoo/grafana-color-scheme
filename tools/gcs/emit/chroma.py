def _xml(p: Palette, v: Variant, counterpart: str) -> str:
    styles = _token_styles(v)
    lines = [
        f"<!-- {HEADER} -->",
        f'<style name="{v.id}" counterpart="{counterpart}">',
        f'  <entry type="Background" style="{v.text["fg"]} bg:{v.surfaces["base"]}"/>',
    ]
    for token, _cls in T.TOKENS:
        if token in T.STRUCTURAL.values() or token in ("Line", "CodeLine", "LineLink", "LineTableTD", "LineTable"):
            continue
        if token == "LineHighlight":
            lines.append(f'  <entry type="LineHighlight" style="bg:{v.surfaces["surface0"]}"/>')
            continue
        if token in ("LineNumbers", "LineNumbersTable"):
            lines.append(f'  <entry type="{token}" style="{v.text["faint"]}"/>')
            continue
        hexv, attrs = styles[token]
        spec = " ".join(x for x in (attrs, hexv) if x)
        lines.append(f'  <entry type="{token}" style="{spec}"/>')
    lines.append("</style>")
    return "\n".join(lines) + "\n"


def _css(v: Variant, *, scope: str = ".chroma", prefix: str = "") -> list[str]:
    """Chroma-compatible class rules. `prefix` scopes them for the combined
    stylesheet so both variants can live in one file."""
    styles = _token_styles(v)
    out: list[str] = []
    sel = f"{prefix}{scope}"
    out.append(
        f"{sel} {{ color: {v.text['fg']}; background-color: {v.surfaces['base']}; "
        "tab-size: 4; -webkit-text-size-adjust: none; }"
    )
    out.append(f"{prefix}.bg {{ color: {v.text['fg']}; background-color: {v.surfaces['base']}; }}")
    for cls, decl in T.STRUCTURAL.items():
        out.append(f"{sel} .{cls} {{ {decl} }}")
    out.append(f"{sel} .hl {{ background-color: {v.surfaces['surface0']} }}")
    for cls in ("lnt", "ln"):
        out.append(
            f"{sel} .{cls} {{ white-space: pre; user-select: none; margin-right: 0.4em; "
            f"padding: 0 0.4em; color: {v.text['faint']} }}"
        )
    for token, cls in T.TOKENS:
        if cls in T.STRUCTURAL or cls in ("hl", "lnt", "ln", "cl"):
            continue
        hexv, attrs = styles[token]
        decls = []
        if hexv:
            decls.append(f"color: {hexv}")
        if "bold" in attrs:
            decls.append("font-weight: bold")
        if "italic" in attrs:
            decls.append("font-style: italic")
        if "underline" in attrs:
            decls.append("text-decoration: underline")
        if not decls:
            continue
        out.append(f"{sel} .{cls} {{ {'; '.join(decls)} }}")
    return out


def emit(p: Palette) -> dict[str, str]:
    files: dict[str, str] = {}
    ids = {name: v.id for name, v in p.each()}

    for name, v in p.each():
        other = "light" if name == "dark" else "dark"
        files[f"styles/{v.id}.xml"] = _xml(p, v, ids[other])
        body = "\n".join(
            [
                f"/* {HEADER} */",
                f"/* {v.label} for Chroma. Requires markup.highlight.noClasses = false in Hugo. */",
                "",
                *_css(v),
            ]
        )
        files[f"css/{v.id}.css"] = body + "\n"

    dark = p.variant("dark")
    light = p.variant("light")
    auto = [
        f"/* {HEADER} */",
        "/* Both variants in one stylesheet. Follows the reader's system setting,",
        '   and an explicit data-theme="light" | "dark" on the root element wins. */',
        "",
        *_css(light),
        "",
        "@media (prefers-color-scheme: dark) {",
        *[f"  {line}" for line in _css(dark, prefix=":root:not([data-theme='light']) ")],
        "}",
        "",
        *_css(dark, prefix=":root[data-theme='dark'] "),
        "",
        *_css(light, prefix=":root[data-theme='light'] "),
    ]
    files["css/grafana-auto.css"] = "\n".join(auto) + "\n"
    return files
